#[cfg(test)]
mod tests {
    use prost::Message;

    use super::*;

    #[test]
    fn signal_message_field_numbers() {
        let msg = SignalMessageProto {
            ratchet_key: Some(vec![0xAA]),
            counter: Some(0),
            previous_counter: Some(2),
            ciphertext: Some(vec![0xBB, 0xCC]),
        };
        // tag1 bytes, tag2 varint (explicit zero is encoded), tag3 varint, tag4 bytes.
        assert_eq!(hex::encode(msg.encode_to_vec()), "0a01aa100018022202bbcc");
        assert_eq!(SignalMessageProto::decode(&msg.encode_to_vec()[..]).unwrap(), msg);
    }

    #[test]
    fn pre_key_signal_message_field_numbers() {
        let msg = PreKeySignalMessageProto {
            registration_id: Some(1),
            pre_key_id: Some(2),
            signed_pre_key_id: Some(3),
            base_key: Some(vec![4]),
            identity_key: Some(vec![5]),
            message: Some(vec![6]),
        };
        // prost encodes in tag order: 1, 2, 3, 4, 5, 6.
        assert_eq!(hex::encode(msg.encode_to_vec()), "08021201041a0105220106280130 03".replace(' ', ""));
    }

    #[test]
    fn records_round_trip() {
        let record = RecordStructure {
            current_session: Some(SessionStructure {
                session_version: Some(3),
                root_key: Some(vec![1; 32]),
                sender_chain: Some(ChainStructure {
                    sender_ratchet_key: Some(vec![5; 33]),
                    sender_ratchet_key_private: Some(vec![6; 32]),
                    chain_key: Some(ChainKeyStructure { index: Some(4), key: Some(vec![7; 32]) }),
                    message_keys: vec![],
                }),
                pending_pre_key: Some(PendingPreKeyStructure {
                    pre_key_id: Some(9),
                    signed_pre_key_id: Some(1),
                    base_key: Some(vec![5; 33]),
                }),
                ..Default::default()
            }),
            previous_sessions: vec![SessionStructure { session_version: Some(3), ..Default::default() }],
        };
        let bytes = record.encode_to_vec();
        assert_eq!(RecordStructure::decode(&bytes[..]).unwrap(), record);

        let sk = SenderKeyRecordStructure {
            sender_key_states: vec![SenderKeyStateStructure {
                sender_key_id: Some(77),
                sender_chain_key: Some(SenderChainKeyStructure { iteration: Some(0), seed: Some(vec![1; 32]) }),
                sender_signing_key: Some(SenderSigningKeyStructure { public: Some(vec![5; 33]), private: None }),
                sender_message_keys: vec![SenderMessageKeyStructure { iteration: Some(1), seed: Some(vec![2; 32]) }],
            }],
        };
        assert_eq!(SenderKeyRecordStructure::decode(&sk.encode_to_vec()[..]).unwrap(), sk);

        let spk = SignedPreKeyRecordStructure {
            id: Some(1),
            public_key: Some(vec![5; 33]),
            private_key: Some(vec![1; 32]),
            signature: Some(vec![2; 64]),
            timestamp: Some(1_700_000_000_000),
        };
        let bytes = spk.encode_to_vec();
        // fixed64 timestamp → wire type 1 under tag 5 (`0x29`).
        assert!(bytes.windows(1).any(|w| w[0] == 0x29));
        assert_eq!(SignedPreKeyRecordStructure::decode(&bytes[..]).unwrap(), spk);
    }

    #[test]
    fn pre_key_record_matches_keys_rs_encoding() {
        // `crypto::keys::PreKey::to_record` writes the same structure.
        let key = crate::crypto::keys::PreKey::from_private(42, [9u8; 32]);
        let decoded = PreKeyRecordStructure::decode(&key.to_record()[..]).unwrap();
        assert_eq!(decoded.id, Some(42));
        assert_eq!(decoded.public_key.as_deref(), Some(&key.public_serialized()[..]));
        assert_eq!(decoded.private_key.as_deref(), Some(&[9u8; 32][..]));
    }

    #[test]
    fn garbage_does_not_panic() {
        for bytes in [&[0xff, 0xff, 0xff][..], &[0x0a, 0x10][..], &[][..]] {
            let _ = RecordStructure::decode(bytes);
            let _ = SenderKeyRecordStructure::decode(bytes);
            let _ = SignalMessageProto::decode(bytes);
        }
    }
}
