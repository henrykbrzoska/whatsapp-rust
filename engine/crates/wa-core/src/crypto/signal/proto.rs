//! Hand-written `prost` mirrors of the public `WhisperTextProtocol.proto`
//! (wire messages) and `LocalStorageProtocol.proto` (persisted records) of
//! `libsignal-protocol-c` (`package textsecure`, proto2).
//!
//! Every field is `optional` upstream, so every field is an `Option` here:
//! prost then encodes explicitly-set zero values the way proto2 does, and a
//! missing field stays distinguishable from zero. Field numbers are the
//! interoperability contract with WhatsApp and with the Go client's database.
//!
//! They are not generated by `wa-proto/build.rs` on purpose: both upstream
//! files declare `package textsecure`, which would produce two clashing
//! modules (D3 in `docs/PROMPT-PHASE-4.md`).

/// `textsecure.SignalMessage` (`WhisperTextProtocol.proto`).
#[derive(Clone, PartialEq, prost::Message)]
pub struct SignalMessageProto {
    #[prost(bytes = "vec", optional, tag = "1")]
    pub ratchet_key: Option<Vec<u8>>,
    #[prost(uint32, optional, tag = "2")]
    pub counter: Option<u32>,
    #[prost(uint32, optional, tag = "3")]
    pub previous_counter: Option<u32>,
    #[prost(bytes = "vec", optional, tag = "4")]
    pub ciphertext: Option<Vec<u8>>,
}

/// `textsecure.PreKeySignalMessage` (`WhisperTextProtocol.proto`).
#[derive(Clone, PartialEq, prost::Message)]
pub struct PreKeySignalMessageProto {
    #[prost(uint32, optional, tag = "5")]
    pub registration_id: Option<u32>,
    #[prost(uint32, optional, tag = "1")]
    pub pre_key_id: Option<u32>,
    #[prost(uint32, optional, tag = "6")]
    pub signed_pre_key_id: Option<u32>,
    #[prost(bytes = "vec", optional, tag = "2")]
    pub base_key: Option<Vec<u8>>,
    #[prost(bytes = "vec", optional, tag = "3")]
    pub identity_key: Option<Vec<u8>>,
    /// A serialized `SignalMessage` (version byte + proto + MAC).
    #[prost(bytes = "vec", optional, tag = "4")]
    pub message: Option<Vec<u8>>,
}

